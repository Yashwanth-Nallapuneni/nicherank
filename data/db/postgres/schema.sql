-- NicheRank schema v2, frozen with the backend team. PostgreSQL 17.
-- Does not stamp Rails migrations. Existing v1 databases use migrate_v2.sql.
CREATE EXTENSION IF NOT EXISTS vector;
CREATE TABLE IF NOT EXISTS public.universities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  openalex_id text NOT NULL UNIQUE CHECK (openalex_id ~ '^I[0-9]+$'),
  name text NOT NULL,
  short_name text, city text, state text, cs_dept_url text,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.professors (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  openalex_id text NOT NULL UNIQUE CHECK (openalex_id ~ '^A[0-9]+$'),
  university_id bigint NOT NULL REFERENCES public.universities(id),
  name text NOT NULL, title text NOT NULL, homepage_url text, orcid text,
  first_pub_year integer, works_count integer, h_index integer,
  match_confidence text NOT NULL CHECK (match_confidence IN ('high','medium','manual')),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.papers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  openalex_id text NOT NULL UNIQUE CHECK (openalex_id ~ '^W[0-9]+$'),
  title text NOT NULL, abstract text, year integer NOT NULL CHECK (year >= 2015),
  paper_type text NOT NULL CHECK (paper_type IN ('article','conference-paper','preprint','book-chapter')),
  venue text, venue_tier text CHECK (venue_tier IN ('A*','A','B','C')),
  venue_tier_source text CHECK (venue_tier_source IN ('core2023','custom')),
  citations integer CHECK (citations >= 0), doi text, primary_topic text, field text,
  keywords text, is_open_access boolean, oa_url text, language text,
  search_vector tsvector GENERATED ALWAYS AS
    (setweight(to_tsvector('english'::regconfig,coalesce(title,'')), 'A') ||
     setweight(to_tsvector('english'::regconfig,coalesce(keywords,'')), 'A') ||
     setweight(to_tsvector('english'::regconfig,coalesce(primary_topic,'')), 'B') ||
     setweight(to_tsvector('english'::regconfig,coalesce(abstract,'')), 'C')) STORED,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.authorships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  professor_id bigint NOT NULL REFERENCES public.professors(id),
  paper_id bigint NOT NULL REFERENCES public.papers(id),
  position text CHECK (position IN ('first','middle','last')), is_corresponding boolean,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (professor_id, paper_id)
);
CREATE TABLE IF NOT EXISTS public.author_aliases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  professor_id bigint NOT NULL REFERENCES public.professors(id),
  alias_openalex_id text NOT NULL UNIQUE CHECK (alias_openalex_id ~ '^A[0-9]+$'),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.paper_duplicates (
  discarded_openalex_id text PRIMARY KEY CHECK (discarded_openalex_id ~ '^W[0-9]+$'),
  retained_paper_id bigint NOT NULL REFERENCES public.papers(id), reason text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.data_review_cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint text NOT NULL UNIQUE, issue_type text NOT NULL, university text,
  name_or_venue text, candidate_ids text, reason text, status text, resolution text
);
CREATE TABLE IF NOT EXISTS public.dataset_metadata (
  dataset_key text PRIMARY KEY, manifest jsonb NOT NULL, loaded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS index_professors_on_university_id ON public.professors(university_id);
CREATE INDEX IF NOT EXISTS index_authorships_on_paper_id ON public.authorships(paper_id);
CREATE INDEX IF NOT EXISTS index_papers_on_year ON public.papers(year);
CREATE INDEX IF NOT EXISTS index_papers_on_search_vector ON public.papers USING gin(search_vector);
